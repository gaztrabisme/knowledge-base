#!/usr/bin/env python3
"""Audit recorded label-verification decisions; never grade or alter passages.

Run with Python 3 (stdlib only), from any directory. The decision model below is
independent of verify_decide.py: that module is never imported or executed.
The real sheet builder is rerun with ONLY its output I/O redirected to memory;
its generated bytes and the unchanged disk bytes must match the initial hashes.
No files are written, including temporary files or Python bytecode. Git is used
only for `git show HEAD:data/bench/questions.jsonl`.
"""

import builtins
from collections import Counter
from contextlib import redirect_stdout
from fractions import Fraction
import hashlib
import io
import json
import math
from pathlib import Path
import runpy
import subprocess
import sys
from types import SimpleNamespace
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[1]
BENCH = ROOT / "data/bench"
VERIFY = BENCH / "analysis/verify"
COUNTS = {"extra": 258, "wrong": 15, "pos": 60, "neg": 60}
FLAGGED = {"ambiguous", "unanswerable", "leaky"}
sys.dont_write_bytecode = True


class Violation(Exception):
    pass


def require(condition, message):
    if not condition:
        raise Violation(message)


def preview(values):
    return ", ".join(str(v) for v in sorted(values)[:6]) or "none"


def same_set(actual, expected, label):
    require(actual == expected,
            f"{label}: missing [{preview(expected - actual)}]; "
            f"unexpected [{preview(actual - expected)}]")


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, f"duplicate JSON field {key!r}")
        result[key] = value
    return result


def read_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique_object)
    except (ValueError, Violation) as exc:
        raise Violation(f"{path.name}: {exc}") from exc


def read_rows(path, key):
    rows = {}
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line, object_pairs_hook=unique_object)
            require(isinstance(row, dict), "row must be a JSON object")
            value = row.get(key)
            require(isinstance(value, str) and value, f"missing/invalid {key}")
            require(value not in rows, f"duplicate {key} {value}")
            rows[value] = row
        except (ValueError, Violation) as exc:
            raise Violation(f"{path.name}:{line_number}: {exc}") from exc
    return rows


def load_data():
    return SimpleNamespace(
        questions=read_rows(BENCH / "questions.jsonl", "qid"),
        audit=read_rows(BENCH / "analysis/golden-audit.jsonl", "qid"),
        pool=read_rows(BENCH / "analysis/golden-audit-pool.jsonl", "qid"),
        sheet=read_rows(VERIFY / "sheet.jsonl", "id"),
        key=read_rows(VERIFY / "key.jsonl", "id"),
        b=read_rows(VERIFY / "grades-B.jsonl", "id"),
        ref=read_rows(VERIFY / "grades-ref.jsonl", "id"),
        sample=read_json(VERIFY / "ref-sample-ids.json"),
        summary=read_json(VERIFY / "decision-summary.json"),
        output=read_rows(BENCH / "questions_v2.jsonl", "qid"),
    )


def parent_list(values, label):
    require(isinstance(values, list), f"{label}: expected a list")
    require(all(isinstance(p, str) and p and "-p" in p for p in values),
            f"{label}: invalid parent id")
    require(len(set(values)) == len(values), f"{label}: duplicate parent ids")


def input_integrity(d):
    require(len(d.questions) == 150, f"expected 150 original questions, got {len(d.questions)}")
    same_set(set(d.audit), set(d.questions), "audit qids")
    same_set(set(d.pool), set(d.questions), "pool qids")
    for qid, q in d.questions.items():
        require(isinstance(q["query"], str) and isinstance(q["stratum"], str),
                f"{qid}: invalid query/stratum")
        parent_list(q["positive_parents"], f"{qid} original positives")
        a = d.audit[qid]
        require(isinstance(a["note"], str) and isinstance(a["verdict"], str),
                f"{qid}: invalid audit note/verdict")
        for field in ("extra_positive_parents", "wrong_positive_parents"):
            parent_list(a[field], f"{qid} {field}")
        require(not set(a["extra_positive_parents"]) & set(q["positive_parents"]),
                f"{qid}: audit extras already labelled")
        require(set(a["wrong_positive_parents"]) <= set(q["positive_parents"]),
                f"{qid}: audit wrong-label proposal was not an original label")
    require(isinstance(d.summary, dict), "decision summary must be an object")
    return "150 unique questions; audit/pool coverage and original/proposed parent lists valid"


def sheet_structure(d):
    for row in d.sheet.values():
        require(set(row) == {"id", "question", "book", "passage"},
                f"{row['id']}: sheet fields must be exactly id, question, book, passage")
        require(all(isinstance(value, str) for value in row.values()),
                f"{row['id']}: sheet fields must be strings")
    for row in d.key.values():
        require(set(row) == {"id", "set", "qid", "parent_id"},
                f"{row['id']}: invalid key fields")
        require(all(isinstance(value, str) and value for value in row.values()),
                f"{row['id']}: invalid key values")
    same_set(set(d.sheet), set(d.key), "sheet/key ids")
    counts = Counter(row["set"] for row in d.key.values())
    require(counts == COUNTS, f"set counts {dict(counts)} != {COUNTS}")
    return "393 unique matching ids; exact sheet schema; extra/wrong/pos/neg = 258/15/60/60"


def sheet_blinding(d):
    hidden = {row[field] for row in d.key.values() for field in ("set", "parent_id")}
    for row in d.sheet.values():
        for field in ("id", "book"):
            for value in sorted(hidden):
                require(value not in row[field],
                        f"{row['id']}: key value {value!r} appears in sheet {field}")
    return "no set name or parent_id occurs as a substring in any sheet id/book field"


def pair_membership(d):
    pairs, proposals, neg_qids = set(), set(), set()
    for ident, row in d.key.items():
        qid, pid, kind = row["qid"], row["parent_id"], row["set"]
        require(qid in d.questions, f"{ident}: unknown qid {qid}")
        require((qid, pid) not in pairs, f"duplicate pair {qid}/{pid}")
        pairs.add((qid, pid))
        expected_id = "v" + hashlib.sha256(f"42|{qid}|{pid}".encode()).hexdigest()[:10]
        require(ident == expected_id, f"{ident}: not the seed-42 opaque id for its pair")
        require(d.sheet[ident]["question"] == d.questions[qid]["query"],
                f"{ident}: sheet question differs from original")
        if kind in {"extra", "wrong"}:
            proposals.add((kind, qid, pid))
        elif kind == "pos":
            require(pid in d.questions[qid]["positive_parents"]
                    and pid not in d.audit[qid]["wrong_positive_parents"]
                    and d.audit[qid]["verdict"] not in FLAGGED,
                    f"{ident}: ineligible positive control")
        elif kind == "neg":
            eligible = {c["parent_id"] for c in d.pool[qid]["pool"][:10]}
            excluded = set(d.questions[qid]["positive_parents"]) | set(d.audit[qid]["extra_positive_parents"])
            require(pid in eligible - excluded, f"{ident}: ineligible negative control")
            require(qid not in neg_qids, f"{qid}: more than one negative control")
            neg_qids.add(qid)
    expected = {(kind, qid, pid) for qid, a in d.audit.items()
                for kind, field in (("extra", "extra_positive_parents"), ("wrong", "wrong_positive_parents"))
                for pid in a[field]}
    same_set(proposals, expected, "audit/key decision pairs")
    return "273 proposals exactly match audit A; all 120 controls eligible; seed-42 ids valid"


def rebuild_sheet():
    paths = [VERIFY / "sheet.jsonl", VERIFY / "key.jsonl"]
    before = {path: path.read_bytes() for path in paths}
    buffers = {}
    original_open, original_io_open = builtins.open, io.open

    class CapturedBytes(io.BytesIO):
        def close(self):
            # Preserve generated bytes after the builder closes its text stream.
            if not self.closed:
                self.saved = self.getvalue()
                super().close()

    def capture_open(file, mode="r", buffering=-1, encoding=None, errors=None,
                     newline=None, closefd=True, opener=None, *, reader=original_open):
        if not any(flag in mode for flag in "wax+"):
            return reader(file, mode, buffering, encoding, errors, newline, closefd, opener)
        path = Path(file).resolve()
        require(path in before and mode == "w" and path not in buffers,
                f"builder attempted unexpected write: {file} ({mode})")
        buffer = CapturedBytes()
        buffers[path] = buffer
        return io.TextIOWrapper(buffer, encoding=encoding, errors=errors, newline=newline)

    def capture_io_open(*args, **kwargs):
        return capture_open(*args, **kwargs, reader=original_io_open)

    def existing_directory(path, mode=0o777, parents=False, exist_ok=False):
        require(path.resolve() == VERIFY and path.is_dir() and exist_ok,
                f"builder attempted unexpected mkdir: {path}")

    builder = ROOT / "scripts/build_verify_sheet.py"
    with patch("builtins.open", capture_open), patch("io.open", capture_io_open), \
            patch.object(Path, "mkdir", existing_directory), redirect_stdout(io.StringIO()):
        namespace = runpy.run_path(str(builder), run_name="__main__")
    require(namespace.get("SEED") == 42, "builder SEED must be 42")
    same_set(set(buffers), set(before), "builder output paths")
    hashes = []
    for path in paths:
        generated = buffers[path].saved
        after = path.read_bytes()
        digest = hashlib.sha256(before[path]).hexdigest()
        regenerated_digest = hashlib.sha256(generated).hexdigest()
        after_digest = hashlib.sha256(after).hexdigest()
        require(before[path] == generated == after and digest == regenerated_digest == after_digest,
                f"{path.name}: bytes differ; before={digest}, rebuilt={regenerated_digest}, after={after_digest}")
        hashes.append(f"{path.name} before=rebuilt=after SHA256 {digest}")
    return "; ".join(hashes) + " (output captured in memory; disk untouched)"


def grade_coverage(d):
    same_set(set(d.b), set(d.key), "judge B grade ids")
    require(set(d.ref) <= set(d.key), f"unknown reference ids: {preview(set(d.ref) - set(d.key))}")
    for name, grades in (("B", d.b), ("reference", d.ref)):
        for ident, row in grades.items():
            require(type(row.get("grade")) is int and row["grade"] in {0, 1, 2},
                    f"{name}/{ident}: grade must be integer 0, 1 or 2")
    require(isinstance(d.sample, list) and len(d.sample) == 40
            and all(isinstance(i, str) for i in d.sample) and len(set(d.sample)) == 40,
            "reference sample must contain exactly 40 unique string ids")
    require(set(d.sample) <= set(d.key), "reference sample contains unknown ids")
    require(set(d.sample) <= set(d.ref),
            f"reference sample grades missing: {preview(set(d.sample) - set(d.ref))}")
    strata = Counter(d.key[i]["set"] for i in d.sample)
    require(strata == dict.fromkeys(COUNTS, 10), f"reference sample not 10 per set: {dict(strata)}")
    return f"B 393/393; reference {len(d.ref)} unique valid grades; sample 40/40, 10 per set"


def calibration(d):
    pos = sum(d.b[i]["grade"] == 2 for i, k in d.key.items() if k["set"] == "pos")
    neg = sum(d.b[i]["grade"] == 2 for i, k in d.key.items() if k["set"] == "neg")
    agree = sum((d.b[i]["grade"] == 2) == (d.ref[i]["grade"] == 2) for i in d.sample)
    rates = Fraction(pos, 60), Fraction(neg, 60), Fraction(agree, 40)
    calibrated = rates[0] >= Fraction(9, 10) and rates[1] <= Fraction(1, 10) and rates[2] >= Fraction(17, 20)
    return dict(zip(("pos_control_rate_B", "neg_control_rate_B", "agreement_B_ref_on_sample"), rates),
                n_sample=40, B_calibrated=calibrated)


def compare_summary(d, expected):
    for field, value in expected.items():
        actual = d.summary.get(field)
        if isinstance(value, Fraction):
            valid = (type(actual) in (int, float) and math.isfinite(actual)
                     and abs(actual - float(value)) <= 1e-9)
        else:
            valid = type(actual) is type(value) and actual == value
        require(valid, f"summary {field}: recorded {actual!r}, recomputed {value}")


def check_calibration(d):
    cal = calibration(d)
    compare_summary(d, cal)
    return (f"pos={cal['pos_control_rate_B']} ({float(cal['pos_control_rate_B']):.12g}); "
            f"neg={cal['neg_control_rate_B']} ({float(cal['neg_control_rate_B']):.12g}); "
            f"agreement={cal['agreement_B_ref_on_sample']}; B_calibrated={cal['B_calibrated']}; summary matches")


def check_kappa(d):
    # Integer contingency counts keep this independent of the production formula.
    cells = Counter((k["set"] == "extra", d.b[i]["grade"] == 2)
                    for i, k in d.key.items() if k["set"] in {"extra", "wrong"})
    n = sum(cells.values())
    agree = cells[True, True] + cells[False, False]
    a2 = cells[True, True] + cells[True, False]
    b2 = cells[True, True] + cells[False, True]
    chance_numerator = a2 * b2 + (n - a2) * (n - b2)
    denominator = n * n - chance_numerator
    require(denominator != 0, "Cohen's kappa undefined: degenerate marginals")
    kappa = Fraction(n * agree - chance_numerator, denominator)
    compare_summary(d, {"kappa_A_B_2_vs_not2": kappa, "n_decision": n})
    return f"A/B binary agreement {agree}/{n}; kappa={kappa} ({float(kappa):.16g}); summary matches"


def required_reference(d):
    calibrated = calibration(d)["B_calibrated"]
    return {i for i, k in d.key.items() if k["set"] in {"extra", "wrong"}
            and (not calibrated or d.b[i]["grade"] != (2 if k["set"] == "extra" else 0))}


def check_reference(d):
    required = required_reference(d)
    require(required <= set(d.ref), f"rule 2 reference grades missing: {preview(required - set(d.ref))}")
    compare_summary(d, {"reference_adjudicated": len(required)})
    return f"all {len(required)} required decision ids graded; sample/decision union covered; summary matches"


def decision_model(d):
    """Construct expected positives solely from raw audit, grades and original labels."""
    required = required_reference(d)
    require(required <= set(d.ref), f"cannot decide: missing reference ids {preview(required - set(d.ref))}")
    additions, removals = {}, set()
    for ident, k in d.key.items():
        kind = k["set"]
        if kind not in {"extra", "wrong"}:
            continue
        via_ref = ident in required
        grade = (d.ref if via_ref else d.b)[ident]["grade"]
        pair = (k["qid"], k["parent_id"])
        if kind == "extra" and grade == 2:
            additions[pair] = "added:ref2" if via_ref else "added:A2,B2"
        if kind == "wrong" and grade == 0:
            removals.add(pair)
    flagged = {qid for qid, a in d.audit.items() if a["verdict"] in FLAGGED}
    expected, rejected, empty = {}, set(), set()
    for qid, q in d.questions.items():
        if qid in flagged:
            continue
        provenance = {pid: "original" for pid in q["positive_parents"] if (qid, pid) not in removals}
        specific = q["stratum"] == "new-books" and "Specificity: specific" in d.audit[qid]["note"]
        own_books = {pid.rsplit("-p", 1)[0] for pid in q["positive_parents"]}
        for (extra_qid, pid), source in additions.items():
            if extra_qid != qid:
                continue
            if specific and pid.rsplit("-p", 1)[0] not in own_books:
                rejected.add((qid, pid))
            else:
                provenance[pid] = source
        if provenance:
            expected[qid] = provenance
        else:
            empty.add(qid)
    stats = {"dropped_flagged": len(flagged), "specific_extras_rejected": len(rejected),
             "added": sum(source.startswith("added:") for prov in expected.values() for source in prov.values()),
             "removed": sum(qid not in flagged for qid, _ in removals),
             "dropped_no_positive": len(empty), "rows": len(expected)}
    return SimpleNamespace(expected=expected, additions=additions, removals=removals,
                           flagged=flagged, rejected=rejected, empty=empty, stats=stats)


def check_provenance(d, model):
    counts = Counter()
    for qid, row in d.output.items():
        require(qid in d.questions, f"v2 unknown qid {qid}")
        parent_list(row["positive_parents"], f"{qid} v2 positives")
        require(isinstance(row.get("provenance"), dict), f"{qid}: missing/invalid provenance")
        same_set(set(row["provenance"]), set(row["positive_parents"]), f"{qid} provenance keys")
        unchanged = {k: v for k, v in row.items() if k not in {"positive_parents", "provenance"}}
        original = {k: v for k, v in d.questions[qid].items() if k != "positive_parents"}
        require(unchanged == original, f"{qid}: non-label question fields changed")
        for pid, source in row["provenance"].items():
            wanted = model.expected.get(qid, {}).get(pid)
            require(wanted is not None and source == wanted,
                    f"{qid}/{pid}: provenance {source!r}, rules expect {wanted!r}")
            counts[source] += 1
    return f"all {sum(counts.values())} positives have exact rule-derived provenance {dict(counts)}; metadata unchanged"


def check_additions(d, model):
    excluded_flagged = sum(qid in model.flagged for qid, _ in model.additions)
    for pair, source in model.additions.items():
        qid, pid = pair
        present = qid in d.output and pid in d.output[qid]["positive_parents"]
        excluded = qid in model.flagged or pair in model.rejected
        require(present != excluded, f"{qid}/{pid}: added={present}, excluded by rule 3/4={excluded}")
    return (f"{len(model.additions)} rule-approved extras: {model.stats['added']} present, "
            f"{excluded_flagged} excluded by flagged questions, {len(model.rejected)} by specificity")


def check_removals(d, model):
    for qid, pid in model.removals:
        require(qid not in d.output or pid not in d.output[qid]["positive_parents"],
                f"{qid}/{pid}: rule-removed label remains")
    for qid, expected in model.expected.items():
        actual = set(d.output.get(qid, {}).get("positive_parents", []))
        originals = {pid for pid, source in expected.items() if source == "original"}
        require(originals <= actual, f"{qid}: retained originals missing [{preview(originals - actual)}]")
    return (f"{len(model.removals)} removal decisions absent ({model.stats['removed']} outside flagged questions); "
            "all other originals in surviving questions retained")


def check_drops(d, model):
    same_set(set(d.output), set(model.expected), "v2 qids")
    dropped = set(d.questions) - set(d.output)
    same_set(dropped, model.flagged | model.empty, "dropped qids")
    for qid, expected in model.expected.items():
        same_set(set(d.output[qid]["positive_parents"]), set(expected), f"{qid} complete positive set")
    compare_summary(d, {"rows": len(d.output)})
    return (f"{len(model.flagged)} flagged + {len(model.empty)} empty ({preview(model.empty)}) = "
            f"{len(dropped)} dropped; {len(d.output)} rows; exact positive sets and summary row count match")


def check_stats(d, model):
    compare_summary(d, model.stats)
    return "; ".join(f"{key}={value}" for key, value in model.stats.items()) + "; summary matches"


def check_head():
    result = subprocess.run(["git", "--no-optional-locks", "show", "HEAD:data/bench/questions.jsonl"],
                            cwd=ROOT, capture_output=True, check=False)
    require(result.returncode == 0, "git show failed: " + result.stderr.decode(errors="replace").strip())
    working = (BENCH / "questions.jsonl").read_bytes()
    require(result.stdout == working, "questions.jsonl differs byte-for-byte from git HEAD")
    return f"questions.jsonl equals git HEAD; {len(working)} bytes; SHA256 {hashlib.sha256(working).hexdigest()}"


def main():
    failures = []

    def check(name, function):
        try:
            detail = function()
        except (Exception, SystemExit) as exc:
            failures.append(name)
            print(f"FAIL {name}: {type(exc).__name__}: {str(exc).replace(chr(10), ' ')}")
            return False
        print(f"PASS {name}: {detail}")
        return True

    # Independent checks still run if some JSON inputs are malformed.
    check("original-unchanged", check_head)
    check("sheet-rebuild", rebuild_sheet)
    try:
        data = load_data()
    except Exception as exc:
        print(f"FAIL raw-inputs: {type(exc).__name__}: {str(exc).replace(chr(10), ' ')}")
        return 1
    prerequisites = [check(name, lambda f=fn: f(data)) for name, fn in (
        ("input-integrity", input_integrity), ("sheet-structure", sheet_structure),
        ("sheet-blinding", sheet_blinding), ("pair-membership", pair_membership),
        ("grade-coverage", grade_coverage))]
    if not all(prerequisites):
        print("SKIP dependent-checks: invalid raw input structure/coverage; see FAIL lines")
        return 1
    check("calibration", lambda: check_calibration(data))
    check("cohen-kappa", lambda: check_kappa(data))
    reference_ok = check("required-reference", lambda: check_reference(data))
    # A stale summary must not prevent checking the actual output decisions.
    if not reference_ok and not required_reference(data) <= set(data.ref):
        print("SKIP decision-checks: missing required reference grades")
        return 1
    model = decision_model(data)
    for name, fn in (("positive-provenance", check_provenance), ("extra-completeness", check_additions),
                     ("removal-completeness", check_removals), ("drops-and-rows", check_drops),
                     ("summary-counts", check_stats)):
        check(name, lambda f=fn: f(data, model))
    return int(bool(failures))


if __name__ == "__main__":
    sys.exit(main())
